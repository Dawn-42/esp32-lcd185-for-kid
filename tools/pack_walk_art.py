"""Technical grid extraction/registration, mirroring and RGB565+A8 conversion."""
from pathlib import Path
from PIL import Image,ImageOps
import json
root=Path(__file__).resolve().parents[1]
atlas=Image.open(root/'assets/walk/walk-atlas.png').convert('RGBA')
tiles=[];bounds=[]
for i in range(8):
    x,y=i%4,i//4
    tile=atlas.crop((round(x*atlas.width/4),round(y*atlas.height/2),round((x+1)*atlas.width/4),round((y+1)*atlas.height/2)))
    mask=tile.getchannel('A').point(lambda a:255 if a>=170 else 0)
    bounds.append(mask.getbbox());tiles.append(tile)
# Common scale and horizontal origin. Align only the grounded paw baseline.
x0=min(b[0] for b in bounds);x1=max(b[2] for b in bounds)
y0=min(b[1] for b in bounds);baseline=max(b[3] for b in bounds)
w,h=128,104;scale=min((w-8)/(x1-x0),(h-8)/(baseline-y0))
frames=[]
for tile,b in zip(tiles,bounds):
    tile=tile.crop((x0,y0,x1,b[3])).resize((round((x1-x0)*scale),round((b[3]-y0)*scale)),Image.Resampling.LANCZOS)
    frame=Image.new('RGBA',(w,h));frame.paste(tile,((w-tile.width)//2,h-4-tile.height));frames.append(frame)
lines=['// Generated by tools/pack_walk_art.py. Grounded, fixed-scale walk frames.','#include "WalkAssets.h"']
header=['#pragma once','#include <lvgl.h>','extern const lv_img_dsc_t *const walk_right[8];','extern const lv_img_dsc_t *const walk_left[8];']
for direction in ['right','left']:
    for i,original in enumerate(frames):
        frame=original if direction=='right' else ImageOps.mirror(original)
        data=bytearray()
        for r,g,b,a in frame.getdata():
            # Reject low-alpha background noise from the generated alpha matte.
            a=0 if a<140 else 255 if a>=240 else round((a-140)*255/100)
            v=((r>>3)<<11)|((g>>2)<<5)|(b>>3);data.extend((v&255,v>>8,a))
        symbol=f'walk_{direction}_{i}'
        lines.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_data[]={{')
        lines+=['  '+','.join(str(v) for v in data[n:n+48])+',' for n in range(0,len(data),48)]
        lines+=['};',f'static const lv_img_dsc_t {symbol}={{',f'.header={{.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.reserved=0,.w={w},.h={h}}},',f'.data_size={len(data)},.data={symbol}_data','};']
    lines.append(f'const lv_img_dsc_t *const walk_{direction}[8]={{'+','.join(f'&walk_{direction}_{i}' for i in range(8))+'};')
# Four-legged stationary turn poses, normalized to the same foot baseline.
turn_atlas=Image.open(root/'assets/walk/turn-atlas.png').convert('RGBA')
turn_tiles=[];turn_bounds=[]
for i in range(4):
    x,y=i%2,i//2
    tile=turn_atlas.crop((round(x*turn_atlas.width/2),round(y*turn_atlas.height/2),round((x+1)*turn_atlas.width/2),round((y+1)*turn_atlas.height/2)))
    b=tile.getchannel('A').point(lambda a:255 if a>=170 else 0).getbbox()
    turn_tiles.append(tile);turn_bounds.append(b)
turn_scale=min((h-8)/max(b[3]-b[1] for b in turn_bounds),(w-8)/max(b[2]-b[0] for b in turn_bounds))
turn_frames=[]
for tile,b in zip(turn_tiles,turn_bounds):
    tile=tile.crop(b).resize((round((b[2]-b[0])*turn_scale),round((b[3]-b[1])*turn_scale)),Image.Resampling.LANCZOS)
    frame=Image.new('RGBA',(w,h));frame.paste(tile,((w-tile.width)//2,h-4-tile.height));turn_frames.append(frame)
turn_frames.append(ImageOps.mirror(turn_frames[3]))
for i,frame in enumerate(turn_frames):
    data=bytearray()
    for r,g,b,a in frame.getdata():
        a=0 if a<140 else 255 if a>=240 else round((a-140)*255/100)
        v=((r>>3)<<11)|((g>>2)<<5)|(b>>3);data.extend((v&255,v>>8,a))
    symbol=f'walk_turn_{i}'
    lines.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_data[]={{')
    lines+=['  '+','.join(str(v) for v in data[n:n+48])+',' for n in range(0,len(data),48)]
    lines+=['};',f'static const lv_img_dsc_t {symbol}={{',f'.header={{.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.reserved=0,.w={w},.h={h}}},',f'.data_size={len(data)},.data={symbol}_data','};']
header+=['extern const lv_img_dsc_t *const walk_turn[3];','extern const lv_img_dsc_t *const walk_stand[2];']
lines+=['const lv_img_dsc_t *const walk_turn[3]={&walk_turn_0,&walk_turn_1,&walk_turn_2};','const lv_img_dsc_t *const walk_stand[2]={&walk_turn_3,&walk_turn_4};']
(root/'firmware/YouyouSpace/WalkAssets.h').write_text('\n'.join(header)+'\n')
(root/'firmware/YouyouSpace/WalkAssets.c').write_text('\n'.join(lines)+'\n')
(root/'assets/walk/manifest.json').write_text(json.dumps({'frames':21,'size':[w,h],'bytes':w*h*3*21,'foot_baseline':h-4,'registration':'common scale, common horizontal origin, aligned grounded paws','bounds':bounds},indent=2))
print('Walk: 21 predecoded walk/turn/stand frames,',w*h*3*21,'flash bytes')
