"""Technical slicing, alpha trimming and LVGL RGB565+A8 export of pet sprites."""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
atlas=Image.open(root/'assets/v4/pet-atlas.png').convert('RGBA')
names=['baby','young','adult','happy','feed','bath','play','sleep','blink','half','stretch','dirty',
       'food_icon','bath_icon','play_icon','litter_icon']
spec=[(name,i,(144,144) if i<12 else (48,48)) for i,name in enumerate(names)]
spec += [('tray',15,(160,92)),('bowl',12,(88,62))]
header=['#pragma once','#include <lvgl.h>']
lines=['// Generated by tools/pack_pet_art.py; no runtime PNG decoder required.','#include "PetAssets.h"']
total=0
for name,cell,size in spec:
    x,y=cell%4,cell//4
    tile=atlas.crop((round(x*atlas.width/4),round(y*atlas.height/4),round((x+1)*atlas.width/4),round((y+1)*atlas.height/4)))
    bounds=tile.getchannel('A').point(lambda a:255 if a>=128 else 0).getbbox()
    if not bounds:raise ValueError(name)
    tile=tile.crop(bounds)
    # A little padding protects fur and consistent sprite anchors during rotation.
    scale=min((size[0]-8)/tile.width,(size[1]-8)/tile.height)
    sampled=tile.resize((max(1,round(tile.width*scale)),max(1,round(tile.height*scale))),Image.Resampling.LANCZOS)
    tile=Image.new('RGBA',size)
    tile.paste(sampled,((size[0]-sampled.width)//2,(size[1]-sampled.height)//2))
    data=bytearray()
    for r,g,b,a in tile.getdata():
        a=0 if a<32 else 255 if a>=240 else a
        v=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        data.extend((v&255,v>>8,a))
    symbol='pet_'+name
    header.append(f'LV_IMG_DECLARE({symbol});')
    lines.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_data[]={{')
    lines += ['  '+','.join(str(v) for v in data[n:n+48])+',' for n in range(0,len(data),48)]
    lines += ['};',f'const lv_img_dsc_t {symbol}={{',
              f'.header={{.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.reserved=0,.w={size[0]},.h={size[1]}}},',
              f'.data_size={len(data)},.data={symbol}_data','};']
    total+=len(data)
(root/'firmware/YouyouSpace/PetAssets.h').write_text('\n'.join(header)+'\n')
(root/'firmware/YouyouSpace/PetAssets.c').write_text('\n'.join(lines)+'\n')
(root/'assets/v4/pet-manifest.json').write_text(json.dumps({'sprites':len(spec),'bytes':total,'format':'RGB565+A8'},indent=2))
print(f'Packed {len(spec)} pet sprites, {total} flash bytes')
