"""Slice a regular generated atlas and export fixed-size RGB565+A8 LVGL assets.

Only technical atlas extraction, sampling and pixel-format conversion happen here.
The original generated PNG is retained unchanged in assets/v4.
"""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
atlas=Image.open(root/'assets/v4/silver-space-atlas.png').convert('RGBA')
names=['cat_open','cat_half','cat_blink','cat_happy','cat_sleep','cat_fed','cat_play','cat_stretch',
       'rover_left','rover_front','rover_right','rocket','moon','mars','saturn','cake']
spec=[]
for i,name in enumerate(names):
    size=(156,156) if i<8 else (96,96) if i<11 else (64,64) if i==11 else (76,76) if i<15 else (208,104)
    spec.append((name,i,size,i==15))
spec += [('cat_icon',0,(62,62),False),('cat_badge',3,(54,54),False),
         ('rover_icon',9,(66,66),False),('cake_icon',15,(62,44),True)]
for i,name in enumerate(['moon','mars','saturn']):
    spec.append((name+'_badge',12+i,(50,50),False))
output=['// Generated by tools/pack_art.py. Assets are RGB565 + alpha, not runtime PNGs.','#include "ArtAssets.h"']
header=['#pragma once','#include <lvgl.h>']
total=0
for name,cell,size,body in spec:
    col,row=cell%4,cell//4
    box=(round(col*atlas.width/4),round(row*atlas.height/4),round((col+1)*atlas.width/4),round((row+1)*atlas.height/4))
    tile=atlas.crop(box)
    if body:
        # Independently generated candle-free cake: preserve all cream tips.
        tile=Image.open(root/'assets/v4/cake-source.png').convert('RGBA')
        bounds=tile.getchannel('A').point(lambda a:255 if a>=64 else 0).getbbox()
        if not bounds:raise ValueError('Cake has no visible alpha')
        tile=tile.crop(bounds)
    tile=tile.resize(size,Image.Resampling.LANCZOS)
    data=bytearray()
    for r,g,b,a in tile.getdata():
        # Quantized low alpha is invisible on the small display and can be skipped.
        a=0 if a<32 else 255 if a>=240 else a
        rgb=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        data.extend((rgb&255,rgb>>8,a))
    total+=len(data)
    symbol='art_'+name
    header.append(f'LV_IMG_DECLARE({symbol});')
    output.append(f'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {symbol}_data[] = {{')
    output += ['  '+','.join(str(x) for x in data[n:n+48])+',' for n in range(0,len(data),48)]
    output += ['};',f'const lv_img_dsc_t {symbol} = {{',
               f' .header = {{.cf=LV_IMG_CF_TRUE_COLOR_ALPHA,.always_zero=0,.reserved=0,.w={size[0]},.h={size[1]}}},',
               f' .data_size={len(data)},.data={symbol}_data','};']
(root/'firmware/YouyouSpace/ArtAssets.h').write_text('\n'.join(header)+'\n')
(root/'firmware/YouyouSpace/ArtAssets.c').write_text('\n'.join(output)+'\n')
(root/'assets/v4/space-manifest.json').write_text(json.dumps({'source':str(atlas.size),'packed_bytes':total,'sprites':len(spec),'format':'RGB565+A8'},indent=2))
print(f'Packed {len(spec)} sprites; {total} flash bytes; no PNG decoding on device')
