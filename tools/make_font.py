"""Build a small LVGL 8 font from system Noto Sans CJK (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
source = ''.join((root / ('firmware/YouyouSpace/'+name)).read_text() for name in ['SceneView.cpp','PixelCity.h'])
chars = sorted(set(source) & set(chr(i) for i in range(0x4E00, 0xA000)) | set(chr(i) for i in range(32, 127)) | {'！', '，', '？', '：', '·'})
def generate(size,name):
    font = ImageFont.truetype('/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', size)
    bitmap = []
    descs = ['    {0, 0, 0, 0, 0, 0},']
    for char in chars:
        x0, y0, x1, y1 = font.getbbox(char, anchor='ls')
        w, h = x1-x0, y1-y0
        img = Image.new('L', (max(1, w), max(1, h)))
        ImageDraw.Draw(img).text((-x0, -y0), char, font=font, fill=255, anchor='ls')
        vals = [p >> 4 for p in img.getdata()] if w*h else []
        offset = len(bitmap)
        bitmap.extend((vals[i] << 4) | (vals[i+1] if i+1 < len(vals) else 0) for i in range(0, len(vals), 2))
        descs.append(f'    {{{offset}, {round(font.getlength(char)*16)}, {w}, {h}, {x0}, {-y1}}},')
    codes = ', '.join(str(ord(c)-32) for c in chars)
    rows = ['    '+', '.join(f'0x{v:02x}' for v in bitmap[i:i+20])+',' for i in range(0, len(bitmap), 20)]
    out = '''// Generated by tools/make_font.py; Noto Sans CJK, SIL Open Font License.
    #include <lvgl.h>
    static const uint8_t bitmap[] = {
    %s
    };
    static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {
    %s
    };
    static const uint16_t unicode_list[] = {%s};
    static const lv_font_fmt_txt_cmap_t cmaps[] = {{
        .range_start = 32, .range_length = %d, .glyph_id_start = 1,
        .unicode_list = unicode_list, .glyph_id_ofs_list = NULL,
        .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }};
    static lv_font_fmt_txt_dsc_t font_dsc = {
        .glyph_bitmap = bitmap, .glyph_dsc = glyphs, .cmaps = cmaps,
        .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
        .kern_classes = 0, .bitmap_format = 0
    };
    const lv_font_t youyou_font = {
        .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
        .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
        .line_height = 31, .base_line = 6, .subpx = LV_FONT_SUBPX_NONE,
        .underline_position = -2, .underline_thickness = 1, .dsc = &font_dsc
    };
    ''' % ('\n'.join(rows), '\n'.join(descs), codes, ord(chars[-1])-31, len(chars))
    (root / f'firmware/YouyouSpace/{name}.c').write_text(out.replace('youyou_font',name).replace('.line_height = 31',f'.line_height = {size+8}'))
    print(f'Font: {len(chars)} characters, {len(bitmap)} bitmap bytes')

generate(23,'youyou_font')
generate(16,'youyou_small')
